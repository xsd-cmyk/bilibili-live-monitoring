package com.example.bilimonitor.domain.policy

/**
 * 通知聚合的判定规则 —— **阈值是"触发合并的条件"，不是"一条通知装多少位"**。
 *
 * ## 语义（用户定稿）
 * 同一个聚合窗口（默认 5 秒）内需要发通知的主播：
 *  - **超过**阈值 → 把这批主播**全部**合并成**一条**通知；
 *  - 不超过阈值 → 逐条单独发。
 *
 * 也就是阈值回答的是"多少位算多、值得合并"，而不是"每条通知里放多少位"。
 * 这不是措辞问题：把阈值当成"每批装多少"，会让"阈值 4 + 10 位主播同时开播"
 * 变成 3 条通知（4＋4＋2），而用户要的是 1 条含全部 10 位的通知。
 *
 * 判定放在窗口**关闭时**做（而不是刚达到阈值就锁定），这样窗口内稍后开播的主播
 * 也会进入同一条通知。窗口默认只有 5 秒，因此"等窗口关闭"的代价是秒级。
 *
 * 单独抽成对象是为了能纯 JVM 单测（判定规则是这次改动的本体，必须有测试钉住边界）。
 */
object NotificationAggregationPolicy {

    /**
     * 是否要把这批主播合并成一条通知。
     *
     * **严格大于**：阈值 N 的含义是"超过 N 位"，正好 N 位不合并（逐条单独发）。
     */
    fun shouldMergeAll(pendingCount: Int, threshold: Int): Boolean = pendingCount > threshold

    /**
     * 是否使用聚合窗口（事件先绑进窗口、等窗口关闭再定案）。
     *
     * 配置校验保证 `threshold >= 1`，因此阈值 1 的含义是"2 位以上就合并"。
     * **不能**再要求 `threshold > 1`（原实现如此）：那会把阈值 1 静默变成"完全不聚合"，
     * 与"超过 1 位就合并"的说法自相矛盾。
     */
    fun usesAggregationWindow(enabled: Boolean, threshold: Int): Boolean = enabled && threshold >= 1
}
